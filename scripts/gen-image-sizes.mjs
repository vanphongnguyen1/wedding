// Generates lib/image-sizes.ts — real width/height (EXIF-aware) of every photo in public/images.
// Run after adding photos:  node scripts/gen-image-sizes.mjs
import sharp from "sharp";
import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join, posix, sep } from "node:path";

const ROOT = "public";
const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : /\.(jpe?g|png|webp)$/i.test(f) ? [p] : [];
});

const entries = [];
for (const file of walk(join(ROOT, "images")).sort()) {
  const m = await sharp(file).metadata();
  let [w, h] = [m.width, m.height];
  if ((m.orientation ?? 1) >= 5) [w, h] = [h, w];
  const url = "/" + posix.join(...file.split(sep).slice(1));
  entries.push(`  ${JSON.stringify(url)}: [${w}, ${h}],`);
}

writeFileSync("lib/image-sizes.ts", `// AUTO-GENERATED by scripts/gen-image-sizes.mjs — do not edit by hand.
// Real [width, height] of each photo so layouts can respect its orientation.

export const IMAGE_SIZES: Record<string, readonly [number, number]> = {
${entries.join("\n")}
};

/** Width / height of a photo (defaults to 2:3 portrait if unknown). */
export function aspectOf(src: string): number {
  const s = IMAGE_SIZES[src];
  return s ? s[0] / s[1] : 2 / 3;
}

export function isLandscape(src: string): boolean {
  return aspectOf(src) > 1;
}
`);
console.log(`lib/image-sizes.ts: ${entries.length} images`);
